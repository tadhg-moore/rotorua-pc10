source("calibration/sa/sa_common.R")
t0 <- Sys.time()
b <- if (file.exists(file.path(SA_DIR, "sa_base_aeme.rds"))) list(aeme = readRDS(file.path(SA_DIR, "sa_base_aeme.rds")), path = file.path(SA_DIR, "build", "sa_base")) else sa_build("sa_base")
message("build+first run: ", round(difftime(Sys.time(), t0, units = "mins"), 1), " min")
saveRDS(b$aeme, file.path(SA_DIR, "sa_base_aeme.rds"))
tab <- sa_table(b)
saveRDS(tab, file.path(SA_DIR, "sa_table.rds"))
print(table(tab$theme))
print(tab[tab$theme != "fixed", c("name", "group", "index", "value", "min", "max", "scale")], row.names = FALSE)
t1 <- Sys.time()
out <- sa_eval(b$aeme, b$path, tab)
message("one evaluation incl. CSPS: ", round(difftime(Sys.time(), t1, units = "mins"), 1), " min")
print(round(out[grep("^(mix|anox|load|chl|sys)_", names(out))], 4))
saveRDS(out, file.path(SA_DIR, "sa_baseline_out.rds"))
